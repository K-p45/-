/**
 * 所有知识点动画的「数据表」。
 * 整个工程只有这一个 Remotion 工程 + 一个 Scene 模板组件（Scene.tsx），
 * 换章节 / 加知识点只需要在这张表里加一条，然后跑 npm run render。
 *
 * 结构：一个 Scene = 3 个「分镜」（beats），每段 18 秒，分镜之间有转场，
 * 页内还有逐条揭示、数字滚动等细节动画 —— 保证「不停留在一页」。
 */

export type Card = { icon: string; title: string; sub: string };
export type Row = { label: string; a: string; b: string };
export type Stat = { value: string; unit: string; label: string };

/** 分镜：pitch 立论 / explain 展开 / apply 落地 */
export type Beat = 'pitch' | 'explain' | 'apply';

export type Scene = {
  id: string;
  kicker: string;
  title: string;
  accent: string;
  accent2: string;
  duration: number;

  /** 分镜 1：开场立论（大字 + 一句话） */
  pitch: { big: string; sub: string; tags: string[] };
  /** 分镜 2：展开（卡片 / 对比表 / 数字 / 步骤） */
  explain: {
    heading: string;
    cards?: Card[];
    rows?: Row[];
    stats?: Stat[];
    steps?: string[];
    notes?: string[];
  };
  /** 分镜 3：落地（要点 + 横向流程） */
  apply: {
    heading: string;
    bullets: string[];
    steps: string[];
  };
};

